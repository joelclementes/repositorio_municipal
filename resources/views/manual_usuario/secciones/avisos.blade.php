<div class="prose prose-vino max-w-none">
    <h1 class="text-3xl md:text-4xl font-extrabold text-vino-900 mb-6 tracking-tight">Módulo de Avisos</h1>

    <p class="text-gray-700 text-lg leading-relaxed mb-6">
        Los <strong>Avisos</strong> permiten a los administradores del sistema publicar anuncios importantes, circulares, comunicados oficiales o recordatorios, los cuales son visibles por todos los entes o entes específicos al momento de ingresar a la plataforma.
    </p>

    <h2 class="text-2xl font-bold text-vino-800 mt-10 mb-4 border-b border-gray-200 pb-3">Estructura de un Aviso</h2>
    <p class="text-gray-700 mb-6">
        Al ingresar al sistema (Dashboard), los usuarios verán los avisos que se encuentren vigentes. Un aviso típicamente consta de la siguiente información:
    </p>
    
    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-8">
        <div class="bg-vino-50 p-4 rounded-lg border border-vino-100">
            <h4 class="font-bold text-vino-900 flex items-center mb-1"><span class="text-xl mr-2">📌</span> Título</h4>
            <p class="text-sm text-gray-700">Resumen claro y conciso del comunicado que se desea transmitir.</p>
        </div>
        <div class="bg-vino-50 p-4 rounded-lg border border-vino-100">
            <h4 class="font-bold text-vino-900 flex items-center mb-1"><span class="text-xl mr-2">📝</span> Contenido</h4>
            <p class="text-sm text-gray-700">El cuerpo completo del aviso, con instrucciones, detalles o fundamentos del mensaje.</p>
        </div>
        <div class="bg-vino-50 p-4 rounded-lg border border-vino-100 md:col-span-2">
            <h4 class="font-bold text-vino-900 flex items-center mb-1"><span class="text-xl mr-2">⏱️</span> Vigencia</h4>
            <p class="text-sm text-gray-700">Rango de fechas (inicio y fin) durante las cuales el aviso será desplegado a los usuarios de manera obligatoria.</p>
        </div>
    </div>

    <div class="bg-white border-l-4 border-gray-400 p-5 shadow-sm my-6 rounded-r-lg">
        <p class="text-gray-600 italic mb-0 text-lg">
            "Esta es la principal vía de comunicación unilateral oficial dentro del sistema, ideal para notificar aperturas de períodos de entrega, cierres inminentes o actualizaciones normativas."
        </p>
    </div>
</div>
